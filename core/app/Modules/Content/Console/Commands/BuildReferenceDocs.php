namespace Juwri\Modules\Content\Console\Commands;

use App\Http\Controllers\DeveloperDocsController;
use Illuminate\Console\Command;

/**
 * Dev MCP P2-4: write the GENERATED reference pages of the docs corpus
 * (themes/drops.md, themes/filters.md, themes/tags.md) from the same
 * reflection the engine/docs use, so search_docs hits them too. `--check`
 * diffs instead of writing (non-zero exit on drift) — wired into the test
 * suite so a committed corpus can never go stale against the code.
 */
class BuildReferenceDocs extends Command
{
    protected $signature = 'docs:build-reference {--check : Diff against committed files instead of writing}';

    protected $description = 'Write (or verify with --check) the generated reference docs in resources/docs/dev';

    public function handle(): int
    {
        $files = [
            'themes/drops.md'   => $this->dropsDoc(),
            'themes/filters.md' => $this->filtersDoc(),
            'themes/tags.md'    => $this->tagsDoc(),
        ];

        $base = resource_path('docs/dev');
        $dirty = [];

        foreach ($files as $rel => $content) {
            $path = $base.'/'.$rel;
            if ($this->option('check')) {
                if (! is_file($path) || file_get_contents($path) !== $content) {
                    $dirty[] = $rel;
                }
                continue;
            }
            @mkdir(dirname($path), 0755, true);
            file_put_contents($path, $content);
            $this->info("wrote {$rel}");
        }

        if ($this->option('check') && $dirty !== []) {
            $this->error('Reference docs are stale: '.implode(', ', $dirty).'. Run: php artisan docs:build-reference');

            return self::FAILURE;
        }

        if ($this->option('check')) {
            $this->info('Reference docs are current.');
        }

        return self::SUCCESS;
    }

    private function dropsDoc(): string
    {
        $out = ["# Liquid drops (objects)\n",
            "GENERATED by `docs:build-reference` from the engine's Drop classes — do not edit by hand.",
            "Properties listed are exactly what a template can touch; nothing else exists.\n"];

        foreach (DeveloperDocsController::dropReference() as $drop => $props) {
            $out[] = '## '.$drop;
            foreach ($props as $p) {
                $out[] = "- `{$p['name']}` ({$p['type']})";
            }
            $out[] = '';
        }

        return implode("\n", $out);
    }

    private function filtersDoc(): string
    {
        $out = ["# Liquid filters (theme-specific)\n",
            "GENERATED by `docs:build-reference` from ThemeFilters — do not edit by hand.",
            "Standard Liquid core filters also work; anything else fails validation.\n",
            '## Whitelisted filters', ''];

        foreach (DeveloperDocsController::filterReference() as $filter) {
            $out[] = "- `{$filter}`";
        }
        $out[] = '';

        return implode("\n", $out);
    }

    private function tagsDoc(): string
    {
        $out = ["# Custom Liquid tags\n",
            "GENERATED by `docs:build-reference` from the engine's tag registrations — do not edit by hand.",
            "Standard Liquid core tags also work.\n"];

        foreach (DeveloperDocsController::tagReference() as $tag) {
            $out[] = "## {% {$tag['name']} %} ({$tag['kind']})";
            $out[] = "Syntax: `{$tag['syntax']}`\n";
            $out[] = $tag['description'];
            $out[] = "\nExample:\n```liquid\n{$tag['example']}\n```\n";
        }

        return implode("\n", $out);
    }
}
