#!/usr/bin/env python3
"""Generate kit/<theme>/css/tokens.css and kit/<theme>/css/preset-<id>.css from tokens/<theme>.json.
Python 3 stdlib only. tools/check_derived.py imports FORMULAS/mix/on_colour from here."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEMES = ['table', 'brew', 'basket', 'aisle', 'book', 'carely']
ROLES = ['primary', 'background', 'surface', 'text', 'accent']
STATUS = ['danger', 'success', 'warning']

# Derived colours: token -> (mix colour, mix % of that colour, into base colour). Same formula for all themes.
# CSS: color-mix(in srgb, var(--x-A) P%, var(--x-B))
FORMULAS = {
    'light': {'surface-2': ('text', 4, 'background'), 'muted': ('text', 72, 'background'),
              'border': ('text', 10, 'background'), 'border-strong': ('text', 56, 'surface')},
    'dark':  {'surface-2': ('text', 8, 'surface'), 'muted': ('text', 70, 'background'),
              'border': ('text', 14, 'background'), 'border-strong': ('text', 45, 'surface')},
}
RADIUS_SCALE = {'none': (0, 0, 999 * 0), 'soft': (10, 8, 999), 'round': (18, 14, 999), 'pill': (26, 999, 999)}
DENSITY_SCALE = {'compact': (4, 8, 12, 18), 'cozy': (6, 12, 18, 26), 'comfortable': (8, 16, 24, 36)}
ARABIC = "'IBM Plex Sans Arabic', system-ui, sans-serif"
FONTS = {  # theme -> (heading, body)
    'table': ("'Fraunces', Georgia, serif", "'Plus Jakarta Sans'"),
    'brew': ("'Plus Jakarta Sans'", "'Plus Jakarta Sans'"),
    'basket': ("'Instrument Sans'", "'Instrument Sans'"),
    'aisle': ("'Inter'", "'Inter'"),
    'book': ("'Plus Jakarta Sans'", "'Plus Jakarta Sans'"),
    'carely': ("'Inter'", "'Inter'"),
}

def lum(h):
    c = [int(h[i:i+2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def ratio(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)

def on_colour(fill):
    return '#ffffff' if ratio('#ffffff', fill) >= ratio('#111111', fill) else '#111111'

def mix(a, b, pct):
    """color-mix(in srgb, a pct%, b): linear per channel on 0-255, rounded."""
    A = [int(a[i:i+2], 16) for i in (1, 3, 5)]
    B = [int(b[i:i+2], 16) for i in (1, 3, 5)]
    return '#%02x%02x%02x' % tuple(round(x * pct / 100 + y * (100 - pct) / 100) for x, y in zip(A, B))

def derive(colors, scheme):
    """colors: dict with the 5 roles (hex). Returns dict token->hex."""
    out = {}
    for tok, (a, pct, b) in FORMULAS[scheme].items():
        out[tok.replace('-', '_')] = mix(colors[a], colors[b], pct)
    return out

def mixcss(scheme, tok):
    a, pct, b = FORMULAS[scheme][tok]
    return f"color-mix(in srgb, var(--x-{a}) {pct}%, var(--x-{b}))"

def colour_block(sel, p, scheme, indent='  '):
    c = p[scheme]
    L = [f"{indent}{sel} {{"]
    for r in ROLES:
        L.append(f"{indent}  --x-{r}: var(--tc-{r}, {c[r].lower()});")
    L.append(f"{indent}  --x-on-primary: var(--tc-on-primary, {on_colour(c['primary'])});")
    L.append(f"{indent}  --x-on-accent: var(--tc-on-accent, {on_colour(c['accent'])});")
    for s in STATUS:
        L.append(f"{indent}  --x-{s}: {c[s].lower()};")
    for tok in FORMULAS[scheme]:
        L.append(f"{indent}  --x-{tok}: {mixcss(scheme, tok)};")
    L.append(f"{indent}}}")
    return L

def tokens_css(theme, d):
    p = d['presets'][d['default_preset']]
    rad = d['radius']; card, ctrl, pill = RADIUS_SCALE[rad['default']]
    v = rad['values_px']
    gaps = DENSITY_SCALE[d['spacing'].get('customizer_default', d['spacing']['default'])]
    h, b = FONTS[theme]
    L = [f"/* GENERATED by tools/build_theme_css.py from tokens/{theme}.json (default preset: {d['default_preset']}). DO NOT EDIT. */",
         "/* Components use --x-* only. Fallbacks (the only hex in the theme) live in the scheme blocks below. */", ""]
    L += colour_block(':root,\n:root[data-scheme="light"]', p, 'light', '')
    L.append('')
    L += colour_block(':root[data-scheme="dark"]', p, 'dark', '')
    L.append('')
    L.append('@media (prefers-color-scheme: dark) {')
    L += colour_block(':root[data-scheme="auto"]', p, 'dark', '  ')
    L.append('}')
    L += ['', ':root {', '  /* radius: core scale, plus theme-only radii */',
          f"  --x-r-card: var(--tr-card, {card}px);", f"  --x-r-control: var(--tr-control, {ctrl}px);",
          f"  --x-r-pill: var(--tr-pill, {pill}px);"]
    if 'image' in v: L.append(f"  --x-r-image: {v['image']}px;")
    if 'sheet_top' in v: L.append(f"  --x-r-sheet: {v['sheet_top']}px;")
    if 'slot' in v: L.append(f"  --x-r-slot: {v['slot']}px;")
    L.append('  /* spacing: core density ramp */')
    for i, g in enumerate(gaps, 1):
        L.append(f"  --x-gap-{i}: var(--ts-gap-{i}, {g}px);")
    L.append('  /* fonts */')
    L.append(f"  --x-font-heading: var(--tf-heading, {h}, {ARABIC});")
    L.append(f"  --x-font-body: var(--tf-body, {b}, {ARABIC});")
    m = d['motion']
    L.append('  /* motion */')
    L += [f"  --tm-fast: {m['fast_ms']}ms;", f"  --tm-base: {m['base_ms']}ms;", f"  --tm-slow: {m['slow_ms']}ms;",
          f"  --tm-ease: {m['ease']};"]
    L.append('  /* type scale */')
    for k, px in d['typography']['scale_px'].items():
        L.append(f"  --tt-{k}: {px}px;")
    L.append('}')
    return '\n'.join(L) + '\n'

def preset_css(theme, pid, p):
    def tc(sel, scheme, indent=''):
        c = p[scheme]
        L = [f"{indent}{sel} {{"]
        for r in ROLES:
            L.append(f"{indent}  --tc-{r}: {c[r].lower()};")
        L.append(f"{indent}  --tc-on-primary: {on_colour(c['primary'])};")
        L.append(f"{indent}  --tc-on-accent: {on_colour(c['accent'])};")
        L.append(f"{indent}}}")
        return L
    L = [f"/* GENERATED by tools/build_theme_css.py. Simulates the --tc-* overrides core emits when an owner picks the '{pid}' preset of '{theme}'. Prototypes/screenshots only. */"]
    L += tc(':root', 'light') + [''] + tc(':root[data-scheme="dark"]', 'dark') + ['']
    L += ['@media (prefers-color-scheme: dark) {'] + tc(':root[data-scheme="auto"]', 'dark', '  ') + ['}']
    return '\n'.join(L) + '\n'

def main():
    for t in THEMES:
        d = json.load(open(os.path.join(ROOT, 'tokens', t + '.json')))
        out = os.path.join(ROOT, 'kit', t, 'css'); os.makedirs(out, exist_ok=True)
        open(os.path.join(out, 'tokens.css'), 'w').write(tokens_css(t, d))
        for pid, p in d['presets'].items():
            open(os.path.join(out, f'preset-{pid}.css'), 'w').write(preset_css(t, pid, p))
        print('wrote', t, len(d['presets']) + 1, 'files')

if __name__ == '__main__':
    main()
