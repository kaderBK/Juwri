"""Generate core/tests/Fixtures/theme/contrast_parity.json: the expected values the PHP
ContrastGuard (Juwri\\Modules\\Storefront\\Services\\Theme\\ContrastGuard) must reproduce.

Everything here is computed by the kit's own Python (build_theme_css.py: lum/ratio/mix/derive/on_colour,
check_derived.py: CHECKS), never by PHP. Run once from the repo root and commit the output; it is
deterministic (fixed seed). Re-run only when the kit tools or tokens change.
    python3 tools/themes/tools/make_contrast_fixture.py
"""
import ast, json, os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from build_theme_css import THEMES, ROOT, derive, ratio, on_colour, FORMULAS, mix  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(ROOT)), 'core', 'tests', 'Fixtures', 'theme', 'contrast_parity.json')

# CHECKS lives in check_derived.py, which runs main() on import: read the literal with ast instead.
tree = ast.parse(open(os.path.join(HERE, 'check_derived.py')).read())
CHECKS = next(ast.literal_eval(n.value) for n in tree.body
              if isinstance(n, ast.Assign) and getattr(n.targets[0], 'id', '') == 'CHECKS')
STATUS = {'light': {'danger': '#b42318', 'success': '#1a6b3c', 'warning': '#8a5a00'},
          'dark': {'danger': '#ff8a7a', 'success': '#5fcb8c', 'warning': '#f2c14e'}}
ROLES = ['primary', 'background', 'surface', 'text', 'accent']

def evaluate(roles, scheme):
    dv = derive(roles, scheme)
    u = dict(roles); u.update(dv); u.update(STATUS[scheme])
    u['on_primary'] = on_colour(u['primary']); u['on_accent'] = on_colour(u['accent'])
    checks = [[f, b, ratio(u[f], u[b]), need, ratio(u[f], u[b]) >= need] for f, b, need in CHECKS]
    return {'scheme': scheme, 'roles': roles, 'derived': dv, 'on_primary': u['on_primary'],
            'on_accent': u['on_accent'], 'checks': checks}

def main():
    rnd = random.Random(20261005)
    hexes = ['#000000', '#ffffff', '#767676', '#777777', '#111111', '#b4331a', '#faf6f0', '#1f1a17', '#e8a33d',
             '#137a3e', '#3fd463', '#15171a', '#ffb02e', '#808080', '#7f7f7f', '#ff00ff', '#00ffff', '#0a0a0a']
    hexes += ['#%06x' % rnd.randrange(0x1000000) for _ in range(40)]
    pairs = []
    for i in range(80):
        a, b = rnd.choice(hexes), rnd.choice(hexes)
        pairs.append({'a': a, 'b': b, 'ratio': ratio(a, b)})
    # mix(): includes exact .5 channel cases (banker's vs half-up rounding differs there).
    mixes = []
    for a, b, p in [('#010101', '#000000', 50), ('#030303', '#000000', 50), ('#000000', '#010101', 50),
                    ('#ffffff', '#000000', 4), ('#ffffff', '#000000', 72), ('#808080', '#000000', 25)]:
        mixes.append({'a': a, 'b': b, 'pct': p, 'result': mix(a, b, p)})
    while len(mixes) < 60:
        a, b = rnd.choice(hexes), rnd.choice(hexes)
        p = rnd.choice([4, 8, 10, 14, 45, 56, 70, 72, 50, 25, 75])
        mixes.append({'a': a, 'b': b, 'pct': p, 'result': mix(a, b, p)})
    # kit presets x scheme
    presets = []
    for t in THEMES:
        d = json.load(open(os.path.join(ROOT, 'tokens', t + '.json')))
        for pid, p in d['presets'].items():
            for sc in ('light', 'dark'):
                roles = {r: p[sc][r].lower() for r in ROLES}
                e = evaluate(roles, sc); e.update({'theme': t, 'preset': pid}); presets.append(e)
    # random owner palettes (many fail), both schemes
    owner = []
    for _ in range(60):
        roles = {r: rnd.choice(hexes) for r in ROLES}
        for sc in ('light', 'dark'):
            owner.append(evaluate(roles, sc))
    data = {'_note': 'GENERATED by tools/themes/tools/make_contrast_fixture.py from the kit Python. Do not hand-edit.',
            'formulas': FORMULAS, 'status': STATUS, 'pairs': pairs, 'mixes': mixes,
            'presets': presets, 'owner': owner}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(data, open(OUT, 'w'), indent=1)
    print('wrote', OUT, len(pairs), len(mixes), len(presets), len(owner))

main()
