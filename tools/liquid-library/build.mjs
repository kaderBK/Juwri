/**
 * Theme Studio B3 — section library stylesheet build.
 *
 *   node tools/liquid-library/build.mjs [--library=1] [--check] [--src=DIR --dry]
 *
 * Concatenates + minifies tools/liquid-library/src/{snippets,sections,runtime}/*.css
 * into assets/liquid-library/<v>/library.css (repo root = the web docroot).
 * runtime/*.css is the RUNTIME SKIN: rules for the markup the commerce
 * runtime renders itself (product view, cart, sheets, dialogs, slots …).
 * No dependencies. The build FAILS (exit 1) when any rule breaks the library
 * CSS contract:
 *
 *   - scope     every selector starts with `.mbs-<name>` (the file's section
 *               or snippet name; BEM children `.mbs-<name>__x` / `--x` count);
 *               runtime/*.css selectors start with `.mb-` or `dialog.mb-`
 *               (the runtime's own class namespace) instead
 *   - logical   no physical sides (margin-left, padding-right, left:, right:,
 *               border-*-left/right, float/clear/text-align left|right,
 *               translateX) — RTL must work without overrides
 *   - tokens    colours only via var(--tc-*, <fallback>) — no raw hex / rgb()
 *               / hsl() / named colours outside a var() fallback
 *   - hygiene   no url(), @import or 100vh; @keyframes named mbs-<name>-*
 *               (runtime: mb-<name>-*)
 *   - orphans   a sections/<type>.css needs core/resources/liquid-library/
 *               <v>/sections/<type>.liquid
 *   - budget    library.css ≤ 15 KB gzipped (what diners download) and ≤ 96 KB raw
 *
 * --check verifies the committed file is up to date instead of writing it.
 * --src=DIR reads the sources from DIR/{snippets,sections,runtime} and --dry
 * validates (contract + budget) without writing — used by the test suite.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const BUDGET = 96 * 1024;      // raw ceiling
const GZ_BUDGET = 15 * 1024;   // gzipped — the real transfer cost (spec §7)

const args = process.argv.slice(2);
const version = (args.find((a) => a.startsWith('--library=')) || '--library=1').split('=')[1];
const checkOnly = args.includes('--check');
const dryRun = args.includes('--dry');
const srcArg = (args.find((a) => a.startsWith('--src=')) || '').slice(6);
if (!/^[0-9]+(\.[0-9]+)*$/.test(version)) fail([`invalid library version "${version}"`]);

const SRC = srcArg || join(HERE, 'src');
const OUT = join(ROOT, 'assets', 'liquid-library', version, 'library.css');
const LIB = join(ROOT, 'core', 'resources', 'liquid-library', version);

const PHYSICAL_PROP = /^(margin|padding|border|scroll-margin|scroll-padding)-(left|right)(-|$)|^border-(top|bottom)-(left|right)-radius$|^(left|right)$/;
const PHYSICAL_VALUE_PROPS = new Set(['float', 'clear', 'text-align', 'caption-side', 'justify-self', 'justify-items', 'resize']);
const NAMED_COLOR = /(^|[\s,(])(white|black|red|green|blue|gray|grey|orange|yellow|purple|pink|silver|navy|teal|maroon|olive|lime|aqua|fuchsia)(?=$|[\s,);!])/i;

const errors = [];
const chunks = [];

for (const kind of ['snippets', 'sections', 'runtime']) {
  const dir = join(SRC, kind);
  if (!existsSync(dir)) continue;
  // runtime/base.css goes first: the other runtime files refine its shared controls.
  const files = readdirSync(dir).filter((f) => f.endsWith('.css')).sort();
  if (kind === 'runtime' && files.includes('base.css')) files.unshift(...files.splice(files.indexOf('base.css'), 1));
  for (const file of files) {
    const name = basename(file, '.css');
    const rel = `${kind}/${file}`;
    if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) {
      errors.push(`${rel}: file name must be a lowercase slug`);
      continue;
    }
    if (kind === 'sections' && !existsSync(join(LIB, 'sections', `${name}.liquid`))) {
      errors.push(`${rel}: no matching section core/resources/liquid-library/${version}/sections/${name}.liquid`);
    }
    const source = readFileSync(join(dir, file), 'utf8');
    let tree;
    try {
      tree = parse(stripComments(source));
    } catch (e) {
      errors.push(`${rel}: ${e.message}`);
      continue;
    }
    validate(tree, name, rel, kind === 'runtime');
    chunks.push(serialize(tree));
  }
}

if (errors.length) fail(errors);

const css = `/* Storefront section library v${version} - generated by tools/liquid-library/build.mjs; edit src/, not this file. */\n${chunks.join('\n')}\n`;
const bytes = Buffer.byteLength(css, 'utf8');
if (bytes > BUDGET) fail([`library.css is ${bytes} bytes (budget ${BUDGET})`]);
const gz = gzipSync(Buffer.from(css, 'utf8'), { level: 9 }).length;
if (gz > GZ_BUDGET) fail([`library.css is ${gz} bytes gzipped (budget ${GZ_BUDGET})`]);

if (dryRun) {
  console.log(`library.css v${version} valid (${bytes} bytes, ${gz} gzipped, ${chunks.length} files) — dry run, nothing written`);
} else if (checkOnly) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== css) fail([`${OUT} is out of date — run node tools/liquid-library/build.mjs`]);
  console.log(`library.css v${version} up to date (${bytes} bytes, ${gz} gzipped)`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, css);
  console.log(`wrote assets/liquid-library/${version}/library.css (${bytes} bytes, ${gz} gzipped, ${chunks.length} files)`);
}

// ---------------------------------------------------------------------------

function fail(list) {
  for (const e of list) console.error(`✗ ${e}`);
  console.error(`library build failed (${list.length} error${list.length === 1 ? '' : 's'})`);
  process.exit(1);
}

/** Remove comments, string-aware. */
function stripComments(src) {
  let out = '';
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === '"' || c === "'") {
      const end = skipString(src, i);
      out += src.slice(i, end);
      i = end - 1;
    } else if (c === '/' && src[i + 1] === '*') {
      const end = src.indexOf('*/', i + 2);
      if (end === -1) throw new Error('unterminated comment');
      i = end + 1;
      out += ' ';
    } else {
      out += c;
    }
  }
  return out;
}

function skipString(src, i) {
  const q = src[i];
  for (let j = i + 1; j < src.length; j++) {
    if (src[j] === '\\') { j++; continue; }
    if (src[j] === q) return j + 1;
  }
  throw new Error('unterminated string');
}

/**
 * Tiny CSS parser: rules {selector, decls[]} and at-rules {name, prelude,
 * body: nodes[] | decls[] | null}.
 */
function parse(src) {
  let i = 0;
  function nodes(top) {
    const list = [];
    let buf = '';
    while (i < src.length) {
      const c = src[i];
      if (c === '"' || c === "'") { const e = skipString(src, i); buf += src.slice(i, e); i = e; continue; }
      if (c === '{') {
        i++;
        const prelude = buf.trim();
        buf = '';
        if (prelude.startsWith('@')) {
          const m = prelude.match(/^@([a-z-]+)\s*(.*)$/is);
          const name = m[1].toLowerCase();
          const rest = m[2].trim();
          if (['media', 'supports', 'container', 'layer'].includes(name)) list.push({ at: name, prelude: rest, children: nodes(false) });
          else if (name === 'keyframes') list.push({ at: name, prelude: rest, frames: nodes(false) });
          else list.push({ at: name, prelude: rest, decls: decls() });
        } else {
          list.push({ selector: prelude, decls: decls() });
        }
        continue;
      }
      if (c === '}') {
        if (top) throw new Error('unexpected }');
        i++;
        if (buf.trim()) throw new Error(`stray text "${buf.trim()}"`);
        return list;
      }
      if (c === ';' && buf.trim().startsWith('@')) {
        list.push({ at: buf.trim().slice(1).split(/\s/)[0].toLowerCase(), prelude: buf.trim(), statement: true });
        buf = '';
        i++;
        continue;
      }
      buf += c;
      i++;
    }
    if (!top) throw new Error('missing }');
    if (buf.trim()) throw new Error(`stray text "${buf.trim()}"`);
    return list;
  }
  function decls() {
    const out = [];
    let buf = '';
    let depth = 0;
    while (i < src.length) {
      const c = src[i];
      if (c === '"' || c === "'") { const e = skipString(src, i); buf += src.slice(i, e); i = e; continue; }
      if (c === '(') depth++;
      if (c === ')') depth--;
      if (c === '{') throw new Error('nested rule inside a declaration block (nesting is not supported)');
      if ((c === ';' && depth === 0) || c === '}') {
        const d = buf.trim();
        if (d) {
          const k = d.indexOf(':');
          if (k < 1) throw new Error(`bad declaration "${d}"`);
          out.push({ prop: d.slice(0, k).trim().toLowerCase(), value: d.slice(k + 1).trim() });
        }
        buf = '';
        i++;
        if (c === '}') return out;
        continue;
      }
      buf += c;
      i++;
    }
    throw new Error('missing }');
  }
  return nodes(true);
}

function validate(list, name, rel, runtime = false) {
  const kf = `${runtime ? 'mb' : 'mbs'}-${name}-`;
  for (const node of list) {
    if (node.statement) { errors.push(`${rel}: @${node.at} is not allowed`); continue; }
    if (node.children) { validate(node.children, name, rel, runtime); continue; }
    if (node.frames) {
      if (!node.prelude.startsWith(kf)) errors.push(`${rel}: @keyframes ${node.prelude} must be named ${kf}*`);
      for (const f of node.frames) checkDecls(f.decls || [], `${rel} @keyframes ${node.prelude}`);
      continue;
    }
    if (node.at) {
      if (node.at !== 'font-face') errors.push(`${rel}: @${node.at} is not allowed`);
      else errors.push(`${rel}: @font-face belongs to the shell (FontPairs), not the library`);
      continue;
    }
    for (const sel of splitSelectors(node.selector)) {
      if (runtime) {
        if (!runtimeScoped(sel)) errors.push(`${rel}: runtime selector "${sel}" must start with .mb- or dialog.mb-`);
      } else if (!scoped(sel, name)) {
        errors.push(`${rel}: selector "${sel}" is not scoped to .mbs-${name}`);
      }
    }
    checkDecls(node.decls, `${rel} "${node.selector}"`);
  }
}

function splitSelectors(selector) {
  const parts = [];
  let depth = 0;
  let buf = '';
  for (const c of selector) {
    if (c === '(') depth++;
    if (c === ')') depth--;
    if (c === ',' && depth === 0) { parts.push(buf.trim()); buf = ''; continue; }
    buf += c;
  }
  parts.push(buf.trim());
  return parts.filter(Boolean);
}

/** `.mbs-<name>` then end, a non-identifier char, or a BEM `__` / `--` child. */
function scoped(sel, name) {
  const root = `.mbs-${name}`;
  if (!sel.startsWith(root)) return false;
  const rest = sel.slice(root.length);
  return rest === '' || /^(__|--)/.test(rest) || /^[^a-zA-Z0-9_-]/.test(rest);
}

/** Runtime skin: the commerce runtime's own `.mb-*` classes (a native <dialog> may be qualified). */
function runtimeScoped(sel) {
  return /^(dialog)?\.mb-[a-z0-9]/.test(sel);
}

function checkDecls(decls, where) {
  for (const { prop, value } of decls) {
    if (PHYSICAL_PROP.test(prop)) errors.push(`${where}: physical property "${prop}" — use the logical equivalent`);
    if (PHYSICAL_VALUE_PROPS.has(prop) && /\b(left|right)\b/i.test(value)) errors.push(`${where}: "${prop}: ${value}" — use start/end`);
    if (/translatex\s*\(/i.test(value) || prop === 'translate' && /^-?[\d.]+(px|%|rem|em)?\s/.test(value)) errors.push(`${where}: horizontal translate flips in RTL`);
    if (/url\s*\(/i.test(value)) errors.push(`${where}: url() is not allowed (no external or bundled assets)`);
    if (/\b100(d|s|l)?vh\b/i.test(value)) errors.push(`${where}: 100vh — heights must be capped`);
    if (!prop.startsWith('--')) {
      const bare = stripVars(value);
      if (/#[0-9a-f]{3,8}\b/i.test(bare) || /\b(rgba?|hsla?|hwb|lab|lch|oklab|oklch)\(\s*[\d.]/i.test(bare) || NAMED_COLOR.test(bare)) {
        errors.push(`${where}: raw colour in "${prop}: ${value}" — use var(--tc-*, <fallback>)`);
      }
    }
  }
}

/** Replace every var(...) (fallbacks included) with a placeholder. */
function stripVars(value) {
  let out = '';
  for (let i = 0; i < value.length; i++) {
    if (value.startsWith('var(', i)) {
      let depth = 0;
      let j = i + 3;
      for (; j < value.length; j++) {
        if (value[j] === '(') depth++;
        if (value[j] === ')') { depth--; if (depth === 0) break; }
      }
      out += 'VAR';
      i = j;
    } else {
      out += value[i];
    }
  }
  return out;
}

function minifyValue(v) {
  let out = '';
  for (let i = 0; i < v.length; i++) {
    const c = v[i];
    if (c === '"' || c === "'") { const e = skipString(v, i); out += v.slice(i, e); i = e - 1; continue; }
    out += c;
  }
  return out.replace(/\s+/g, ' ').replace(/\s*,\s*/g, ',').replace(/\(\s+/g, '(').replace(/\s+\)/g, ')').trim();
}

function minifySelector(s) {
  return splitSelectors(s).map((p) => p.replace(/\s+/g, ' ').replace(/\s*>\s*/g, '>').replace(/\s*\+\s*/g, '+').replace(/\s*~\s*/g, '~')).join(',');
}

function serialize(list) {
  let out = '';
  for (const node of list) {
    if (node.children) out += `@${node.at} ${minifyValue(node.prelude)}{${serialize(node.children)}}`;
    else if (node.frames) out += `@keyframes ${node.prelude}{${node.frames.map((f) => `${f.selector}{${decl(f.decls)}}`).join('')}}`;
    else if (node.selector) out += `${minifySelector(node.selector)}{${decl(node.decls)}}`;
  }
  return out;
}

function decl(decls) {
  return decls.map(({ prop, value }) => `${prop}:${minifyValue(value)}`).join(';');
}
